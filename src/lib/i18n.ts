const dicts = { en, de }

export function t(key: Key, vars: Record<string, string | number> = {}): string {
  const s = dicts[settings.lang][key] ?? en[key]
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''))
}

const locale = () => (settings.lang === 'de' ? 'de-DE' : 'en-GB')

export function ago(ts: number): string {
  const diff = Date.now() - ts
  const rtf = new Intl.RelativeTimeFormat(locale(), { numeric: 'auto' })
  const min = Math.round(diff / 60_000)
  if (min < 1) return t('time.justNow')
  if (min < 60) return rtf.format(-min, 'minute')
  const h = Math.round(min / 60)
  if (h < 24) return rtf.format(-h, 'hour')
  const d = Math.round(h / 24)
  if (d < 7) return rtf.format(-d, 'day')
  if (d < 35) return rtf.format(-Math.round(d / 7), 'week')
  const mo = Math.round(d / 30)
  if (mo < 12) return rtf.format(-mo, 'month')
  return rtf.format(-Math.round(d / 365), 'year')
}

export function date(ts: number, withYear = false): string {
  const d = new Date(ts)
  const sameYear = d.getFullYear() === new Date().getFullYear()
  return new Intl.DateTimeFormat(locale(), { day: 'numeric', month: 'long', ...(withYear || !sameYear ? { year: 'numeric' } : {}) }).format(d)
}

export function monthYear(ts: number): string {
  return new Intl.DateTimeFormat(locale(), { month: 'long', year: 'numeric' }).format(new Date(ts))
}

export function speechLang(): string {
  return settings.lang === 'de' ? 'de-DE' : 'en-GB'
}
